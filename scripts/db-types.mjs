// Generates src/backend/database.types.ts from the local Supabase stack (`supabase start` first).
// `--check` compares instead of writing and fails when the committed file has drifted from the
// migrations (CI runs it after `supabase db reset`).
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const TARGET = "src/backend/database.types.ts";
const HEADER = "// Generated by `pnpm db:types` from the local stack. Do not edit by hand.\n";

const check = process.argv.includes("--check");

const generated = execFileSync(
  "supabase",
  ["gen", "types", "typescript", "--local", "--schema", "public"],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
);

// Format exactly like the committed file, so the comparison ignores the CLI's whitespace.
const dir = mkdtempSync(join(tmpdir(), "coii-types-"));
const file = join(dir, "database.types.ts");
try {
  writeFileSync(file, HEADER + generated);
  execFileSync("pnpm", ["exec", "oxfmt", file], { stdio: "inherit" });
  const formatted = readFileSync(file, "utf8");
  if (!check) {
    writeFileSync(TARGET, formatted);
    console.log(`wrote ${TARGET}`);
  } else if (readFileSync(TARGET, "utf8") !== formatted) {
    console.error(
      `${TARGET} is out of date with the migrations. Run \`pnpm db:types\` and commit.`,
    );
    process.exitCode = 1;
  } else {
    console.log(`${TARGET} matches the migrations`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
